"""Extract AppTheme colour tables from MicroCode/Models/AppState.swift into C# source."""
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("enum AppTheme: String, CaseIterable {")
end = src.index("\n}\n", start)
body = src[start:end]
cases = re.findall(r"case (\w+) = \"(\w+)\"", body)
names = [c[0] for c in cases]
props = ["editorBackground","editorText","keywordColor","stringColor","commentColor","numberColor","typeColor","functionColor","selectionColor","lineHighlightColor"]

def parse_color(expr, prop, table):
    expr = expr.strip()
    m = re.match(r"NSColor\(red: ([\d.]+), green: ([\d.]+), blue: ([\d.]+), alpha: ([\d.]+)\)", expr)
    if m: return tuple(float(x) for x in m.groups())
    m = re.match(r"NSColor\(calibratedRed: ([\d.]+), green: ([\d.]+), blue: ([\d.]+), alpha: ([\d.]+)\)", expr)
    if m: return tuple(float(x) for x in m.groups())
    m = re.match(r"NSColor\(white: ([\d.]+), alpha: ([\d.]+)\)", expr)
    if m: w, a = float(m.group(1)), float(m.group(2)); return (w, w, w, a)
    m = re.match(r"NSColor\(srgbRed: ([\d.]+), green: ([\d.]+), blue: ([\d.]+), alpha: ([\d.]+)\)", expr)
    if m: return tuple(float(x) for x in m.groups())
    if expr in ("NSColor.black", ".black"): return (0, 0, 0, 1)
    if expr in ("NSColor.white", ".white"): return (1, 1, 1, 1)
    m = re.match(r"(.+)\.withAlphaComponent\(([\d.]+)\)$", expr)
    if m:
        c = parse_color(m.group(1), prop, table)
        if c: return (c[0], c[1], c[2], float(m.group(2)))
    m = re.match(r"AppTheme\.(\w+)\.(\w+)$", expr)
    if m: return ("ref", m.group(1), m.group(2))
    m = re.match(r"NSApp\?\.effectiveAppearance\.name == \.darkAqua \? (.+?) : (.+)$", expr)
    if m: return parse_color(m.group(1), prop, table)  # Windows build assumes dark appearance for .system
    return None

table = {n: {} for n in names}
unparsed = []
for prop in props:
    m = re.search(r"var %s: NSColor \{\s*switch self \{(.*?)\n    \}\n" % prop, body, re.S)
    if not m:
        unparsed.append(("NOPROP", prop)); continue
    block = m.group(1)
    for cm in re.finditer(r"case ([.\w, ]+?):\s*(?:\n\s*)?return (.+?)(?:\s*//.*)?$", block, re.M):
        targets = [t.strip().lstrip(".") for t in cm.group(1).split(",")]
        col = parse_color(cm.group(2), prop, table)
        if col is None: unparsed.append((prop, targets, cm.group(2)))
        for t in targets:
            if t in table: table[t][prop] = col
# resolve refs
for n in names:
    for p in props:
        v = table[n].get(p)
        guard = 0
        while isinstance(v, tuple) and v and v[0] == "ref" and guard < 5:
            v = table[v[1]].get(v[2]); guard += 1
        table[n][p] = v

for u in unparsed: print("UNPARSED", u, file=sys.stderr)
missing = [(n, p) for n in names for p in props if not table[n].get(p)]
for mm in missing: print("MISSING", mm, file=sys.stderr)

disp = dict(re.findall(r"case \.(\w+): return \"(.*?)\"", body[body.index("var displayName"):body.index("var isDark")]))
dark_false = re.search(r"var isDark: Bool \{\s*switch self \{\s*case (.*?):\s*return false", body, re.S).group(1)
light = [t.strip().lstrip(".") for t in dark_false.split(",")]
glass = ["transparent", "extraClear", "crystalClear", "obsidianGlass"]
dglass = ["dark", "xcodeDark", "keynote", "xnuDark", "obsidianGlass", "transparent", "extraClear"]

def cs(c):
    r, g, b, a = c
    return "C(%s,%s,%s,%s)" % (repr(round(r, 4)), repr(round(g, 4)), repr(round(b, 4)), repr(round(a, 4)))

out = []
out.append("// <auto-generated> Extracted from MicroCode/Models/AppState.swift (enum AppTheme) by tools/extract_themes.py. Do not edit by hand.")
out.append("namespace MicroCode.Core {")
out.append("    public static partial class ThemeTable {")
out.append("        static System.Windows.Media.Color C(double r, double g, double b, double a) { return System.Windows.Media.Color.FromArgb((byte)System.Math.Round(a * 255), (byte)System.Math.Round(r * 255), (byte)System.Math.Round(g * 255), (byte)System.Math.Round(b * 255)); }")
out.append("        public static readonly ThemeDef[] All = new ThemeDef[] {")
for raw, n in [(c[1], c[0]) for c in cases]:
    t = table[n]
    out.append('            new ThemeDef("%s", "%s", %s, %s, %s, %s),' % (raw, disp.get(n, n).replace('"', '\\"'),
        "true" if n not in light else "false", "true" if n in glass else "false",
        "true" if n in dglass else ("null" if n == "system" else "false"),
        ", ".join(cs(t[p]) for p in props)))
out.append("        };")
out.append("    }")
out.append("}")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print("themes:", len(names), "props:", len(props))
